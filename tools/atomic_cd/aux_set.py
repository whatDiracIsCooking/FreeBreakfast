#!/usr/bin/env python3
"""Generate a whole auxiliary basis set: every element of an orbital Basis Set
Exchange document, each run through ``cli.build_aux_shells`` at its default
settings, written as one named BSE document of the kind ``data/aux_basis/``
carries and ``resolve_aux_basis`` finds by its ``name``.

``cli`` builds one element and writes a nameless "minimal" document; this is
the set-level wrapper around it. ``--max-l`` caps every element alike: the
C++ fitting kernels stop at g, so a set meant for them takes ``--max-l 4``,
which binds only where the orbital basis reaches f (Sc-Zn in cc-pVDZ) --
everywhere else 2 l_obs is already at most 4.

From the repo root (``UV_PROJECT_ENVIRONMENT=$PWD/.venv`` inside the
devcontainer, ``tools/README.md``)::

    uv run --group tools python -m tools.atomic_cd.aux_set \\
        data/basis/cc-pVDZ.json cc-pVDZ-acCD --max-l 4

writes ``data/aux_basis/cc-pVDZ-acCD.json``. BLAS is pinned to one thread,
so a rerun writes the same bytes.
"""

from __future__ import annotations

import os

# Before numpy loads its BLAS: one thread, so every reduction runs in one
# order and a rerun regenerates the file byte for byte.
for variable in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[variable] = "1"

import argparse  # noqa: E402
import json  # noqa: E402
import pathlib  # noqa: E402
import sys  # noqa: E402

import pyscf  # noqa: E402
from pyscf.data.elements import ELEMENTS  # noqa: E402

from . import cli, eri_quartet  # noqa: E402

OUT_DIR = pathlib.Path(__file__).resolve().parents[2] / "data" / "aux_basis"

REFERENCE = {
    "reference_description": (
        "Automatic acCD auxiliary set with SVD contraction (S. Lehtola, J. "
        "Chem. Theory Comput. 17, 6886 (2021), arXiv:2106.11081; J. Chem. "
        "Theory Comput. 19, 6242 (2023), arXiv:2306.11039), generated by "
        "tools/atomic_cd"
    ),
    "reference_keys": [],
}


def aux_set(orbital: dict, name: str, source: str, max_l: int | None) -> dict:
    """The auxiliary set of every element in the BSE document `orbital`, as a
    BSE document called `name`; `source` is the orbital file's path, recorded
    in its provenance."""
    threshold = cli.THRESHOLD[True]
    elements = {}
    for z in sorted(orbital["elements"], key=int):
        symbol = ELEMENTS[int(z)]
        basis = eri_quartet.basis_from_bse(orbital, symbol)
        shells, _summary = cli.build_aux_shells(
            symbol,
            basis,
            threshold,
            max_l,
            contract_threshold=cli.CONTRACT_THRESHOLD,
        )
        elements[z] = {
            **cli.to_bse_spherical(symbol, shells)["elements"][z],
            "references": [REFERENCE],
        }
        print(f"{symbol}: {sum(len(v) for v in shells.values())} shells", flush=True)
    function_types = sorted(
        {s["function_type"] for e in elements.values() for s in e["electron_shells"]}
    )
    settings = (
        f"threshold {threshold:g}, contract threshold {cli.CONTRACT_THRESHOLD:g}"
        + (f", max l {max_l}" if max_l is not None else "")
    )
    return {
        "molssi_bse_schema": {"schema_type": "complete", "schema_version": "0.1"},
        "revision_description": (
            f"Generated from {source} by tools/atomic_cd/aux_set.py "
            f"({settings}) over PySCF {pyscf.__version__}"
        ),
        "elements": elements,
        "version": "1",
        "function_types": function_types,
        "names": [name],
        "tags": [],
        "family": "accd",
        "description": f"{name}, an automatic acCD fitting set for {source}",
        "role": "jkfit",
        "auxiliaries": {},
        "name": name,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="atomic_cd.aux_set",
        description="Generate a named acCD auxiliary set for every element "
        "of an orbital BSE document.",
    )
    parser.add_argument("orbital", help="the orbital basis, a BSE JSON document")
    parser.add_argument("name", help="the set's name, e.g. cc-pVDZ-acCD")
    parser.add_argument(
        "--max-l",
        type=int,
        default=None,
        metavar="L",
        help="highest auxiliary angular momentum, every element "
        "(default: 2x each element's highest shell ell)",
    )
    parser.add_argument(
        "-o",
        "--output",
        metavar="PATH",
        help="where to write it (default: data/aux_basis/<name>.json)",
    )
    args = parser.parse_args(argv)
    if args.max_l is not None and args.max_l < 0:
        parser.error(f"--max-l must be >= 0, got {args.max_l}")

    with open(args.orbital, encoding="utf-8") as f:
        orbital = json.load(f)
    document = aux_set(orbital, args.name, args.orbital, args.max_l)
    out = pathlib.Path(args.output) if args.output else OUT_DIR / f"{args.name}.json"
    out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
