#!/usr/bin/env python3
"""Reject a blocking host-device copy: `wwrMemcpy(` or `wwrMemcpy2D(`.

docs/style.md "Host-device copies" is the rule: a copy ordered against a
DeviceResources goes on `res.stream()` with `wwrMemcpyAsync` (or
`wwrMemcpy2DAsync`), then `res.sync()` before the host side is read or goes
away. `res.stream()` is non-blocking, so the null stream a bare `wwrMemcpy`
runs on is not ordered against it, and from pageable memory the copy may
return before it lands. The `Async` forms are not matched: the call must open
straight after the name.

Not flagged:
  - Kernels generated by FelizJueves, as devtools/check-int-types.py skips them.

Comments and string literals are blanked before matching, with
check-int-types.py's helpers (reused, not copied). Same calling convention as
the other commit hooks: pre-commit passes the staged files, CI's `lint` job
passes every tracked C++ file outside deps/. Exits 1 with one
`path:line:col: message` per finding, 0 when clean.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

_INT_TYPES = Path(__file__).resolve().parent / "check-int-types.py"
_spec = importlib.util.spec_from_file_location("check_int_types", _INT_TYPES)
assert _spec is not None and _spec.loader is not None
_int_types = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_int_types)

blank_comments_and_literals = _int_types.blank_comments_and_literals
is_generated = _int_types.is_generated

# The name, whole (not the tail of a longer identifier), then the call's paren.
_BLOCKING = re.compile(r"(?<!\w)wwrMemcpy(?:2D)?\s*\(")


def find_violations(text: str) -> list[tuple[int, int]]:
    """Return (line, column) for each blocking wwrMemcpy call, 1-based."""
    found = []
    code_lines = blank_comments_and_literals(text).split("\n")
    for lineno, code in enumerate(code_lines, 1):
        for m in _BLOCKING.finditer(code):
            found.append((lineno, m.start() + 1))
    return found


def main(argv: list[str]) -> int:
    status = 0
    for name in argv:
        path = Path(name)
        text = path.read_text(encoding="utf-8")
        if is_generated(text):
            continue
        for lineno, col in find_violations(text):
            print(
                f"{name}:{lineno}:{col}: blocking wwrMemcpy -- use wwrMemcpyAsync "
                'on res.stream(), then res.sync(); see docs/style.md "Host-device '
                'copies"'
            )
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
