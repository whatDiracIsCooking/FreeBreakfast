#!/usr/bin/env python3
"""Reject a hand-written ceiling division: `(n + b - 1) / b`.

docs/style.md "Launch shape and integer rounding" is the rule: a ceiling
division is `math::idivup` and a round-up to a multiple is `math::align_up`,
from src/core/primitives/primitives.h, for host and device code alike. The
pattern matched is `+ b - 1) / b` with the same divisor on both sides -- a
plain identifier (`kFourWarps`), a qualified one (`fb::kFourWarps`), or a
braced conversion (`int64_t{kFourWarps}`).

Not flagged:
  - Files in EXEMPT_FILES: primitives.h, where idivup itself is written.
  - Kernels generated by FelizJueves, as devtools/check-int-types.py skips them.

Only the ceiling division is checked. A constant that renames a core one
(`kCiBlock = kFourWarps`) is the same rule's other half, but whether a
derived constant has a meaning of its own is a judgement, so it is left to
review.

Comments and string literals are blanked before matching, with
check-int-types.py's helpers (reused, not copied). Same calling convention as
the other commit hooks: pre-commit passes the staged files, CI's `lint` job
passes every tracked C++ file outside deps/. Exits 1 with one
`path:line:col: message` per finding, 0 when clean.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

_INT_TYPES = Path(__file__).resolve().parent / "check-int-types.py"
_spec = importlib.util.spec_from_file_location("check_int_types", _INT_TYPES)
assert _spec is not None and _spec.loader is not None
_int_types = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_int_types)

blank_comments_and_literals = _int_types.blank_comments_and_literals
is_generated = _int_types.is_generated

EXEMPT_FILES = frozenset({"src/core/primitives/primitives.h"})

# `+ b - 1) / b`, the divisor captured and required again after the slash. The
# trailing lookahead stops `/ kTile` from matching inside `/ kTileKeys`.
_DIVISOR = r"(?:\w+::)*\w+(?:\{[^{}]*\})?"
_CEIL_DIV = re.compile(rf"\+\s*(?P<b>{_DIVISOR})\s*-\s*1\s*\)\s*/\s*(?P=b)(?![\w{{])")


def find_violations(text: str) -> list[tuple[int, int]]:
    """Return (line, column) for each hand-written ceiling division, 1-based."""
    found = []
    code_lines = blank_comments_and_literals(text).split("\n")
    for lineno, code in enumerate(code_lines, 1):
        for m in _CEIL_DIV.finditer(code):
            found.append((lineno, m.start() + 1))
    return found


def main(argv: list[str]) -> int:
    status = 0
    for name in argv:
        path = Path(name)
        if path.as_posix() in EXEMPT_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        if is_generated(text):
            continue
        for lineno, col in find_violations(text):
            print(
                f"{name}:{lineno}:{col}: hand-written ceiling division -- use "
                "math::idivup (or math::align_up) from primitives.h; see "
                'docs/style.md "Launch shape and integer rounding"'
            )
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
