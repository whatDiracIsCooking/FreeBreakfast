"""devtools/check-blocking-memcpy.py: what it flags, and what it must leave alone.

The checker is the only gate on docs/style.md "Host-device copies", so these
cases pin both directions: a bare `wwrMemcpy(` or `wwrMemcpy2D(` is a finding,
and the `Async` forms, longer names that contain it, and prose are not.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[2] / "devtools" / "check-blocking-memcpy.py"
_spec = importlib.util.spec_from_file_location("check_blocking_memcpy", _SCRIPT)
assert _spec is not None and _spec.loader is not None
check = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check)


def lines(source: str) -> list[int]:
    return [line for line, _ in check.find_violations(source)]


@pytest.mark.parametrize(
    "source",
    [
        "wwr::wwrMemcpy(host, dev, bytes, wwr::wwrMemcpyDeviceToHost);",
        "EXPECT_EQ(wwr::wwrMemcpy(h, d, n, kind), wwr::wwrSuccess);",
        "return wwrMemcpy (dst, src, n, kind);",
        "wwr::wwrMemcpy2D(dst, dp, src, sp, w, h, kind);",
        "auto e = wwr::wwrMemcpy(\n    dst, src, n, kind);",
    ],
)
def test_flags_blocking_copy(source: str) -> None:
    assert len(lines(source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "wwr::wwrMemcpyAsync(host, dev, bytes, kind, res.stream());",
        "wwr::wwrMemcpy2DAsync(dst, dp, src, sp, w, h, kind, stream);",
        "const auto kind = wwr::wwrMemcpyDeviceToHost;",
        "my_wwrMemcpy(dst, src, n);",
        "// wwr::wwrMemcpy(dst, src, n, kind) is banned\nauto x = 0;",
        "/* wwrMemcpy( */",
        'auto s = "wwr::wwrMemcpy(";',
    ],
)
def test_leaves_async_and_prose_alone(source: str) -> None:
    assert lines(source) == []


def test_reports_line_and_column() -> None:
    assert check.find_violations("// header\n  wwr::wwrMemcpy(a, b, n, k);\n") == [
        (2, 8)
    ]


def test_main_reports_and_fails(tmp_path: Path, capsys) -> None:
    bad = tmp_path / "k.cpp"
    bad.write_text("auto e = wwr::wwrMemcpy(h, d, n, k);\n")
    good = tmp_path / "ok.cpp"
    good.write_text("auto e = wwr::wwrMemcpyAsync(h, d, n, k, res.stream());\n")
    assert check.main([str(good)]) == 0
    assert check.main([str(bad)]) == 1
    assert "k.cpp:1:15: blocking wwrMemcpy" in capsys.readouterr().out


def test_generated_kernel_is_skipped(tmp_path: Path) -> None:
    generated = tmp_path / "s_00.cu"
    generated.write_text(
        "// s_00: generated by felizjueves.emit.cuda -- do not edit.\n"
        "auto e = wwr::wwrMemcpy(h, d, n, k);\n"
    )
    assert check.main([str(generated)]) == 0
