"""devtools/check-ceil-div.py: what it flags, and what it must leave alone.

The checker is the only gate on the ceiling-division half of docs/style.md
"Launch shape and integer rounding", so these cases pin both directions: a
hand-written `(n + b - 1) / b` is a finding, and idivup, unrelated arithmetic,
prose and primitives.h itself are not.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[2] / "devtools" / "check-ceil-div.py"
_spec = importlib.util.spec_from_file_location("check_ceil_div", _SCRIPT)
assert _spec is not None and _spec.loader is not None
check = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check)


def lines(source: str) -> list[int]:
    return [line for line, _ in check.find_violations(source)]


@pytest.mark.parametrize(
    "source",
    [
        "return (items + kCiBlock - 1) / kCiBlock;",
        "const uint32_t t = (n + kTile - 1) / kTile;",
        "auto s = (hi - lo + kWarpSize - 1) / kWarpSize;",
        "auto b = (static_cast<int64_t>(rows) + kBlock - 1) / kBlock;",
        "auto b = (n+b-1)/b;",
        "auto b = (n + fb::kFourWarps - 1) / fb::kFourWarps;",
        "auto b = (n + int64_t{kFourWarps} - 1) / int64_t{kFourWarps};",
        "return k * ((n + kRadixSortTile - 1) / kRadixSortTile);",
    ],
)
def test_flags_hand_written_ceiling_division(source: str) -> None:
    assert len(lines(source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "return math::idivup(items, int64_t{kFourWarps});",
        "auto m = math::align_up(bytes, kWorkspaceAlignment);",
        "auto t = (n + kTile - 1) / kTileKeys;",
        "auto t = (n + a - 1) / b;",
        "auto t = (n + b - 2) / b;",
        "auto t = (n - 1) / b + 1;",
        "// (n + b - 1) / b is banned\nauto t = math::idivup(n, b);",
        "/* (n + b - 1) / b */",
        'auto s = "(n + b - 1) / b";',
    ],
)
def test_leaves_idivup_and_other_arithmetic_alone(source: str) -> None:
    assert lines(source) == []


def test_reports_line_and_column() -> None:
    assert check.find_violations("// header\n  x = (n + b - 1) / b;\n") == [(2, 10)]


def test_main_reports_and_fails(tmp_path: Path, capsys) -> None:
    bad = tmp_path / "k.cu"
    bad.write_text("auto g = (n + kB - 1) / kB;\n")
    good = tmp_path / "ok.cu"
    good.write_text("auto g = math::idivup(n, kB);\n")
    assert check.main([str(good)]) == 0
    assert check.main([str(bad)]) == 1
    assert "k.cu:1:13: hand-written ceiling division" in capsys.readouterr().out


def test_primitives_h_is_exempt(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)
    defn = Path("src/core/primitives/primitives.h")
    defn.parent.mkdir(parents=True)
    defn.write_text("  return (a + b - 1) / b;\n")
    assert check.main([defn.as_posix()]) == 0


def test_generated_kernel_is_skipped(tmp_path: Path) -> None:
    generated = tmp_path / "s_00.cu"
    generated.write_text(
        "// s_00: generated by felizjueves.emit.cuda -- do not edit.\n"
        "auto g = (n + kB - 1) / kB;\n"
    )
    assert check.main([str(generated)]) == 0
