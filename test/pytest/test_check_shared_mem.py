"""devtools/check-shared-mem.py: what it flags, and what it must leave alone.

The checker is the only gate on docs/style.md "Shared memory", so these cases
pin both directions: a dynamic declaration without a reason is a finding, and
static arrays, prose, and a marked line are not.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

_SCRIPT = Path(__file__).resolve().parents[2] / "devtools" / "check-shared-mem.py"
_spec = importlib.util.spec_from_file_location("check_shared_mem", _SCRIPT)
assert _spec is not None and _spec.loader is not None
check = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check)


def lines(source: str) -> list[int]:
    return [line for line, _ in check.find_violations(source)]


@pytest.mark.parametrize(
    "source",
    [
        "extern __shared__ double smem[];",
        "extern  __shared__ __align__(16) unsigned char raw[];",
        "__shared__ extern float s[];",
        "HIP_DYNAMIC_SHARED(double, smem)",
        "// a comment-only line\nextern __shared__ double smem[];",
        "f();  // dynamic-smem-ok: not a comment-only line\nextern __shared__ int s[];",
        "extern __shared__ double smem[];  // dynamic-smem-ok:",
    ],
)
def test_flags_dynamic_shared_memory(source: str) -> None:
    assert len(lines(source)) == 1


@pytest.mark.parametrize(
    "source",
    [
        "__shared__ double b[kMaxDim * kMaxDim];",
        "template <int32_t N> __global__ void k() { __shared__ float t[N]; }",
        "extern double host_side;",
        "// extern __shared__ is banned\n__shared__ double s[4];",
        "/* extern __shared__ double smem[]; */",
        'auto s = "extern __shared__";',
        "extern __shared__ double smem[];  // dynamic-smem-ok: 96 KiB tile",
        "// dynamic-smem-ok: 96 KiB tile, past the static limit\n"
        "extern __shared__ double smem[];",
    ],
)
def test_leaves_static_and_explained_alone(source: str) -> None:
    assert lines(source) == []


def test_reports_line_and_column() -> None:
    assert check.find_violations("// header\n  extern __shared__ int s[];\n") == [
        (2, 3)
    ]


def test_main_reports_and_fails(tmp_path: Path, capsys) -> None:
    bad = tmp_path / "k.cu"
    bad.write_text("extern __shared__ double smem[];\n")
    good = tmp_path / "ok.cu"
    good.write_text("__shared__ double smem[64];\n")
    assert check.main([str(good)]) == 0
    assert check.main([str(bad)]) == 1
    assert "k.cu:1:1: dynamic shared memory" in capsys.readouterr().out


def test_generated_kernel_is_skipped(tmp_path: Path) -> None:
    generated = tmp_path / "s_00.cu"
    generated.write_text(
        "// s_00: generated by felizjueves.emit.cuda -- do not edit.\n"
        "extern __shared__ double smem[];\n"
    )
    assert check.main([str(generated)]) == 0
