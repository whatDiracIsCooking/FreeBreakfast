"""Write src/boys_series.rs from the C++ tree's generated Boys headers.

    python3 experimental/rust/df_metric/gen_boys_series.py

src/integrals/shared/eval_boys_M.h (FelizJueves's emit, M in 0..20) each
hold one Horner polynomial: the Kummer series of F_M truncated at a fixed
degree. This copies their coefficients, digit for digit and in the headers'
order (highest degree first), into one Rust table per M. Re-run it after
those headers are regenerated.
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHARED = HERE.parents[2] / "src" / "integrals" / "shared"
MAX_ORDER = 20

FIRST = re.compile(r"double s = ([0-9.e+-]+);")
NEXT = re.compile(r"s = fma\(s, x, ([0-9.e+-]+)\);")


def coefficients(order: int) -> list[str]:
    text = (SHARED / f"eval_boys_{order}.h").read_text()
    first = FIRST.findall(text)
    rest = NEXT.findall(text)
    if len(first) != 1 or not rest:
        raise SystemExit(f"eval_boys_{order}.h is not the shape expected")
    declared = re.search(r"SUM_\(k=0\.\.(\d+)\)", text)
    if declared is None or int(declared.group(1)) != len(rest):
        raise SystemExit(f"eval_boys_{order}.h: degree and coefficients disagree")
    return first + rest


def main() -> None:
    out = [
        "//! Generated by `gen_boys_series.py` from the C++ tree's",
        "//! `src/integrals/shared/eval_boys_M.h`; do not edit.",
        "//!",
        "//! `SERIES[M]` is the Kummer series of `F_M`,",
        "//! `SUM_k c_k x^k`, `c_k = 1 / ((2M+1)(2M+3)...(2M+2k+1))`, truncated",
        "//! where the tail is under 2^-53 of the sum for `x = 2T < 2 (M + 8)`:",
        "//! its coefficients, highest degree first, as Horner takes them.",
        "",
        "/// The highest order the tables cover.",
        f"pub(crate) const MAX_ORDER: usize = {MAX_ORDER};",
        "",
        "/// Each order's coefficients, highest degree first.",
        "#[rustfmt::skip]",
        f"pub(crate) const SERIES: [&[f64]; {MAX_ORDER + 1}] = [",
    ]
    for order in range(MAX_ORDER + 1):
        out.append(f"    // F_{order}")
        out.append("    &[")
        out += [f"        {c}," for c in coefficients(order)]
        out.append("    ],")
    out.append("];")
    (HERE / "src" / "boys_series.rs").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
