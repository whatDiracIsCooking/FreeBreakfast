//! `src/io/sad` (module `free_breakfast.io.sad`): the compiled-in SAD
//! atomic densities, every `data/sad/<basis>/<Z>.npy`, found by basis-set
//! name and atomic number. Host code that links nothing.
//!
//! A domain crate over the format crate `fb-io-npy`, as `fb-io-basis` is
//! over its JSON. Its one function is an `fb_sad::SadStampLookup`:
//! `fb-sad` takes it as a parameter rather than depending on this crate, so
//! the generator that writes the files can run the SCF without linking its
//! own output.
//!
//! **Compiled in** for the reason the basis sets are: the tree installs
//! nothing, and a stamp that lives in the binary cannot go missing beside
//! it. `build.rs` writes the table, one `include_bytes!` per file, so a
//! regenerated `data/sad/` needs no edit here.
//!
//! **The key is the directory name**, compared exactly with
//! `fb_basis::BasisSet::name`: no spelling is folded, since only a basis
//! resolved from the binary carries a name, and it carries the canonical
//! one. A directory that names no `data/basis` set, which the C++ configure
//! refuses, fails a unit test here; a file stem that is not a three-digit Z
//! fails the build, as there.
//!
//! | C++ (`free_breakfast`) | Here |
//! |---|---|
//! | `builtin_sad_density(basis, z)` | [`builtin_sad_density`]`(basis, z)`, an `fb_sad::SadStampLookup` |
//! | `builtin_sad.cpp.in`'s `BuiltinSad` and `kBuiltinSad` | the private table `BUILTIN` of `(basis, z, bytes)`, generated by `build.rs` |
//! | `CMakeLists.txt`'s generation, and its checks of each stem and directory name | `build.rs`, which checks the stem; the directory name is checked by the unit test `every_directory_names_a_compiled_in_basis` |

#![forbid(unsafe_code)]

use fb_core_error_handling::{Error, check_or_abort};
use fb_io_npy::parse_npy;

include!(concat!(env!("OUT_DIR"), "/builtin_sad.rs"));

/// The baked SAD density of element `z` in the compiled-in basis set
/// `basis`, or `None` if this crate carries none: `builtin_sad_density`.
///
/// The block is the atom's converged spherically averaged density over its
/// own spherical AOs, `n × n` flat column-major, `n` the atom's spherical
/// AO count: what `fb_sad::sad_density`'s SCF computes for that atom,
/// written ahead of time.
///
/// `basis` is the set's canonical name exactly as
/// `fb_basis::BasisSet::name` holds it (`cc-pVDZ`), not a spelling to
/// fold. Safe to call concurrently: it reads constant data and parses a
/// copy.
///
/// Aborts the process, through [`check_or_abort`], on bytes that do not
/// parse as a square matrix: they are this build's own, so a bad one is a
/// broken build, and falling back to the SCF would only hide it.
pub fn builtin_sad_density(basis: &str, z: i32) -> Option<Vec<f64>> {
    let (_, _, npy) = BUILTIN
        .iter()
        .find(|(name, element, _)| *name == basis && *element == z)?;
    let array = check_or_abort(parse_npy(npy));
    if array.shape.len() != 2 || array.shape[0] != array.shape[1] {
        check_or_abort::<()>(Err(Error::io(format!(
            "builtin SAD stamp {basis}/{z:03}.npy is not a square matrix"
        ))));
    }
    Some(array.data)
}

