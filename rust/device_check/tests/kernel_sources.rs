//! Two rules on the device sources under `rust/` that only their text
//! holds. Tier 3: it reads files and nothing else.
//!
//! - **No launch shape crosses the C ABI** (`docs/gpu_layer.md`, "Launch
//!   shape and dispatch"): every header a kernel library's
//!   `rust/<module>/kernels/fb_<module>.h` reaches through `#include "..."`,
//!   the ones its `-sys` bindings are generated from, names no block, grid,
//!   warp or wavefront, so no wrapper takes a block size and no Rust caller
//!   can learn the warp width from a declaration.
//! - **Emitted units are the generator's, byte for byte**
//!   (`docs/gpu_layer.md`, "Build", "What the port changes"): every file
//!   under `rust/` whose first line says `generated by felizjueves` lies at
//!   `rust/<module>/kernels/<path>` and equals its C++ twin at
//!   `src/<module>/<path>`, which `tools/emit`'s `--out-root` and its
//!   default write from one run. This proves the two trees agree, not that
//!   either matches a fresh run of the generator.

use std::path::{Path, PathBuf};

/// The words, as whole identifier parts, that name a launch shape.
const SHAPE_WORDS: &[&str] = &[
    "block",
    "blocks",
    "grid",
    "warp",
    "warps",
    "wavefront",
    "dim3",
];

/// The marker FelizJueves writes on the first line of every emitted unit.
const EMITTED: &str = "generated by felizjueves";

fn rust_root() -> PathBuf {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    root.canonicalize().unwrap_or(root)
}

/// `source` with `//` and `/* */` comments blanked, newlines kept.
fn strip_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut rest = source;
    while !rest.is_empty() {
        if let Some(r) = rest.strip_prefix("//") {
            let end = r.find('\n').unwrap_or(r.len());
            rest = &r[end..];
        } else if let Some(r) = rest.strip_prefix("/*") {
            let end = r.find("*/").map_or(r.len(), |e| e + 2);
            out.extend(r[..end].chars().filter(|&c| c == '\n'));
            rest = &r[end..];
        } else {
            let c = rest.chars().next().unwrap();
            out.push(c);
            rest = &rest[c.len_utf8()..];
        }
    }
    out
}

/// An identifier's parts, lowercased: split at `_` and at a lower-to-upper
/// step, so `blockDim`, `BLOCK_SIZE` and `fb_block` each yield `block`.
fn parts(word: &str) -> Vec<String> {
    let mut out = Vec::new();
    for piece in word.split('_') {
        let mut cur = String::new();
        let mut prev_lower = false;
        for c in piece.chars() {
            if c.is_ascii_uppercase() && prev_lower && !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
            cur.push(c.to_ascii_lowercase());
        }
        if !cur.is_empty() {
            out.push(cur);
        }
    }
    out
}

/// Each launch-shape name in a header's code, with its line.
fn shape_names(source: &str) -> Vec<(usize, String)> {
    let mut found = Vec::new();
    for (i, line) in strip_comments(source).lines().enumerate() {
        if line.trim_start().starts_with("#include") {
            continue;
        }
        for word in line.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_')) {
            if parts(word)
                .iter()
                .any(|p| SHAPE_WORDS.contains(&p.as_str()))
            {
                found.push((i + 1, word.to_owned()));
            }
        }
    }
    found
}

/// `header` and every header it reaches through `#include "x.h"`, resolved
/// beside the includer or else in `rust/device_headers/`, as
/// `devtools/rust-bindings.py` resolves them. An include found in neither
/// (the C ABI's own) is not read.
fn reached(header: &Path, device_headers: &Path, out: &mut Vec<PathBuf>) {
    let header = header.canonicalize().unwrap();
    if out.contains(&header) {
        return;
    }
    out.push(header.clone());
    let text = std::fs::read_to_string(&header).unwrap();
    for line in strip_comments(&text).lines() {
        let Some(name) = line
            .trim_start()
            .strip_prefix("#include")
            .map(str::trim)
            .and_then(|r| r.strip_prefix('"'))
            .and_then(|r| r.split('"').next())
        else {
            continue;
        };
        let beside = header.parent().unwrap().join(name);
        let shared = device_headers.join(name);
        if beside.is_file() {
            reached(&beside, device_headers, out);
        } else if shared.is_file() {
            reached(&shared, device_headers, out);
        }
    }
}

/// Every `rust/<module>/kernels/fb_<module>.h`.
fn library_headers(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(root).unwrap() {
        let dir = entry.unwrap().path();
        let module = dir.file_name().unwrap().to_string_lossy().into_owned();
        let header = dir.join("kernels").join(format!("fb_{module}.h"));
        if header.is_file() {
            out.push(header);
        }
    }
    out.sort();
    out
}

#[test]
fn no_header_the_bindings_read_names_a_launch_shape() {
    let root = rust_root();
    let headers = library_headers(&root);
    assert!(
        headers
            .iter()
            .any(|h| h.ends_with("recipes/kernels/fb_recipes.h")),
        "{headers:?}"
    );
    let mut files = Vec::new();
    for h in &headers {
        reached(h, &root.join("device_headers"), &mut files);
    }
    let mut failures = Vec::new();
    for file in &files {
        let text = std::fs::read_to_string(file).unwrap();
        for (line, name) in shape_names(&text) {
            failures.push(format!(
                "{}:{line}: `{name}`: a launch wrapper's C declarations take dimensions, \
                 never a block, grid or warp width; the wrapper picks the launch shape \
                 (docs/gpu_layer.md, \"Launch shape and dispatch\")",
                file.strip_prefix(&root).unwrap_or(file).display()
            ));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// The scan sees a shape in a parameter, a constant or a type, in any case,
/// and not in a comment, an include, or a word that only contains one.
#[test]
fn the_shape_scan_sees_parameters_and_constants() {
    let src = "\
        #include \"block_params.h\"\n\
        /// launch with one block per class\n\
        fb_launch_status fb_x(uint32_t n, uint32_t block_size, wwr_stream s);\n\
        #define FB_X_WARP_SIZE ((uint32_t)32)\n\
        void fb_y(dim3 g, int blockDim);\n\
        typedef int32_t fb_gridline;\n\
        uint32_t fb_blocked_count(void);\n";
    let got: Vec<(usize, String)> = shape_names(src);
    let want: Vec<(usize, String)> = [
        (3, "block_size"),
        (4, "FB_X_WARP_SIZE"),
        (5, "dim3"),
        (5, "blockDim"),
    ]
    .into_iter()
    .map(|(l, w)| (l, w.to_owned()))
    .collect();
    assert_eq!(got, want);
}

/// Every file under `dir`, skipping build, target and hidden trees.
fn files_under(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy();
        if path.is_dir() {
            if !(name.starts_with("build") || name == "target" || name.starts_with('.')) {
                files_under(&path, out);
            }
        } else {
            out.push(path);
        }
    }
}

/// The C++ twin of an emitted file at `rel` (relative to `rust/`):
/// `<module>/kernels/<path>` is `src/<module>/<path>`. `None` when `rel`
/// is not under a module's `kernels/`.
fn twin(rel: &Path) -> Option<PathBuf> {
    let mut parts = rel.components();
    let module = parts.next()?;
    if parts.next()?.as_os_str() != "kernels" {
        return None;
    }
    Some(Path::new("src").join(module).join(parts.as_path()))
}

/// Each emitted file's failure: not under a module's `kernels/`, no twin,
/// or a twin that differs, with the first line that differs.
fn emitted_failures(rel: &Path, text: &[u8], twin_text: Option<&[u8]>) -> Option<String> {
    let Some(twin) = twin(rel) else {
        return Some(format!(
            "{}: an emitted unit outside rust/<module>/kernels/, where --out-root writes it",
            rel.display()
        ));
    };
    let Some(theirs) = twin_text else {
        return Some(format!(
            "{}: an emitted unit with no C++ twin at {}: emit both trees from one run \
             (tools/emit/*.py, and again with --out-root)",
            rel.display(),
            twin.display()
        ));
    };
    if text == theirs {
        return None;
    }
    let ours = String::from_utf8_lossy(text);
    let theirs = String::from_utf8_lossy(theirs);
    let line = ours
        .lines()
        .zip(theirs.lines())
        .position(|(a, b)| a != b)
        .unwrap_or_else(|| ours.lines().count().min(theirs.lines().count()))
        + 1;
    Some(format!(
        "{}:{line}: differs from {} at its line {line}: an emitted unit is emitted again from \
         the generator, never edited or copied by hand (docs/gpu_layer.md, \"Build\")",
        rel.display(),
        twin.display()
    ))
}

#[test]
fn every_emitted_unit_equals_its_cpp_twin() {
    let root = rust_root();
    let repo = root.parent().unwrap();
    let mut files = Vec::new();
    files_under(&root, &mut files);
    files.sort();
    let mut checked = 0;
    let mut failures = Vec::new();
    for file in &files {
        let Ok(text) = std::fs::read(file) else {
            continue;
        };
        let first = text.split(|&c| c == b'\n').next().unwrap_or(&[]);
        if !String::from_utf8_lossy(first).contains(EMITTED) {
            continue;
        }
        checked += 1;
        let rel = file.strip_prefix(&root).unwrap();
        let theirs = twin(rel).and_then(|t| std::fs::read(repo.join(t)).ok());
        failures.extend(emitted_failures(rel, &text, theirs.as_deref()));
    }
    // At least the Boys routine, so a walk that found nothing fails.
    assert!(checked > 0, "no emitted unit under {}", root.display());
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// A twin that differs fails naming the line, and one missing, or a unit
/// outside a `kernels/`, fails naming where it should be.
#[test]
fn the_twin_check_names_what_differs() {
    let rel = Path::new("integrals/kernels/shared/eval_boys_3.h");
    assert_eq!(
        twin(rel),
        Some(PathBuf::from("src/integrals/shared/eval_boys_3.h"))
    );
    assert_eq!(emitted_failures(rel, b"a\nb\n", Some(b"a\nb\n")), None);
    let differs = emitted_failures(rel, b"a\nb\n", Some(b"a\nc\n")).unwrap();
    assert!(
        differs.starts_with(
            "integrals/kernels/shared/eval_boys_3.h:2: differs from src/integrals/shared/eval_boys_3.h"
        ),
        "{differs}"
    );
    let missing = emitted_failures(rel, b"a\n", None).unwrap();
    assert!(missing.contains("no C++ twin"), "{missing}");
    let outside = emitted_failures(Path::new("device_headers/x.h"), b"a\n", None).unwrap();
    assert!(
        outside.contains("outside rust/<module>/kernels/"),
        "{outside}"
    );
}
